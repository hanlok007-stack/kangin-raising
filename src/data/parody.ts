export function parodyText(t: string): string {
  for (const [a, b] of MAP) t = t.replaceAll(a, b);
  return t;
}

// 팩 전체(이름, 본문, 스테이지, 연표…)에 적용한다. 플래그·id는 영문이라 영향받지 않는다.
export const parody = <T>(x: T): T => JSON.parse(parodyText(JSON.stringify(x)));
